// Typed access to the collection data in src/data/collections.json. Pages read
// products only through this module, so swapping the JSON for a CMS or a
// commerce platform later means changing one file.
import data from '@/data/collections.json';

/** concept: design proposal only · upcoming: confirmed product, not on sale · available: on sale */
export type ProductStatus = 'concept' | 'upcoming' | 'available';
export type VitolaShape = 'parejo' | 'torpedo' | 'belicoso' | 'perfecto';

export type Vitola = { name: string; shape: VitolaShape; lengthMm: number; ringGauge: number };

export type Product = {
  slug: string;
  name: string;
  status: ProductStatus;
  summary: string;
  description: string;
  vitola: Vitola;
  strength: string | null;
  flavorDirection: string[];
  packaging: string | null;
  related: string[];
  // Fields below stay null until the manufacturer confirms them.
  wrapper?: string | null;
  binder?: string | null;
  filler?: string | null;
  countryOfOrigin?: string | null;
  manufacturer?: string | null;
  price?: number | null;
  currency?: string | null;
  /** Verified specifications flip this to 'verified'; until then all specs display as concepts. */
  specStatus?: 'concept' | 'verified';
};

export type Collection = {
  slug: string;
  number: number;
  numeral: string;
  name: string;
  empire: string;
  period: string;
  inspiration: string;
  story: string;
  accent: { name: string; hex: string; on: string };
  emblem: { motif: string; note: string };
  feature?: boolean;
  products: Product[];
};

export const collections = data.collections as Collection[];

export const getCollection = (slug: string) => collections.find((c) => c.slug === slug);

export const allProducts = () => collections.flatMap((c) => c.products.map((p) => ({ product: p, collection: c })));

export function getProduct(slug: string) {
  return allProducts().find(({ product }) => product.slug === slug);
}

export const relatedProducts = (p: Product) =>
  p.related.map((slug) => getProduct(slug)).filter((x): x is NonNullable<typeof x> => Boolean(x));

/** Asset paths generated by scripts/brand/build-assets.mjs. */
export const assets = {
  emblem: (c: Collection) => `/brand/emblems/${c.slug}.svg`,
  emblemOnAccent: (c: Collection) => `/brand/emblems/${c.slug}-on-accent.svg`,
  band: (c: Collection) => `/brand/cigar-bands/${c.slug}-band.svg`,
  boxLid: (c: Collection) => `/brand/packaging/${c.slug}-box-lid.svg`,
  cigar: (p: Product) => `/brand/product/${p.slug}.svg`,
  bandDetail: (p: Product) => `/brand/product/${p.slug}-band-detail.svg`,
};

export const inches = (mm: number) => {
  const eighths = Math.round((mm / 25.4) * 8);
  const whole = Math.floor(eighths / 8);
  const rest = eighths % 8;
  const frac = rest === 0 ? '' : ` ${rest % 2 === 0 ? (rest % 4 === 0 ? `${rest / 4}/2` : `${rest / 2}/4`) : `${rest}/8`}`;
  return `${whole}${frac}″`;
};

